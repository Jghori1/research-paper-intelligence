def _load_cleaned(path: Path = DEFAULT_INPUT) -> pd.DataFrame:
    logger.info("Loading cleaned dataset from %s", path)
    df = pd.read_csv(path)
    logger.info("Loaded %d rows", len(df))
    return df


def _count_entity_mentions(texts: Iterable[str], keywords: Iterable[str]) -> Counter:
    """Count mentions of keywords in texts (case-insensitive).

    Returns a Counter mapping lowercase keyword -> count.
    """
    counter: Counter = Counter()
    kw_list = [k.lower() for k in keywords]
    for t in texts:
        if not isinstance(t, str):
            continue
        s = t.lower()
        for kw in kw_list:
            if kw in s:
                counter[kw] += s.count(kw)
    return counter


def _format_top_list(items: Iterable[Tuple[str, int]], limit: int = 10) -> str:
    lines = []
    for i, (item, count) in enumerate(items):
        if i >= limit:
            break
        lines.append(f"- **{item}** — {count} mentions")
    return "\n".join(lines)


