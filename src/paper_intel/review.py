from __future__ import annotations

"""Generate a literature review Markdown report from the cleaned dataset.

The module loads the cleaned dataset (default: data/processed/cleaned_papers.csv),
computes summary statistics and extracts frequent themes, datasets, benchmarks,
and metrics, and writes a structured Markdown report to reports/report.md.

Design:
- Each section is generated by a dedicated function to keep the code testable.
- Uses the keywords and analyze utilities for token extraction and statistics.
- Uses a small curated list of dataset/benchmark/metric names to detect mentions in
  the corpus; this is intentionally conservative and extendable.
"""

