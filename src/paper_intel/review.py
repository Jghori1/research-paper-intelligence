def research_objective_section() -> str:
    return (
        "# Literature Review\n\n"
        "This report summarizes themes, datasets, benchmarks, and evaluation metrics "
        "found in the corpus of cleaned research paper abstracts. The goal is to "
        "provide a concise synthesis of common research topics and empirical "
        "practices to inform further analysis and meta-research.\n"
    )


def dataset_summary_section(df: pd.DataFrame) -> str:
    total = len(df)
    years_df = publication_counts_by_year(df)
    categories_df = category_frequencies(df).head(10)
    avg_len_df = average_abstract_length(df)

    summary_lines = [
        "## Dataset summary\n",
        f"- Number of papers: **{total}*\n",
    ]

    if not years_df.empty:
        years_preview = years_df.tail(10).to_dict(orient="records")
        summary_lines.append("- Recent publication counts by year (last 10 years):\n")
        for r in years_preview:
            summary_lines.append(f"  - {int(r['year'])}: {int(r['count'])}\n")

    if not categories_df.empty:
        summary_lines.append("- Top categories:\n")
        for _, row in categories_df.iterrows():
            summary_lines.append(f"  - {row['category']}: {int(row['count'])}\n")

    if not avg_len_df.empty:
        row = avg_len_df.iloc[0]
        summary_lines.append(
            f"- Average abstract length: **{row['avg_words']:.1f} words**, median **{row['median_words']:.1f} words**\n"
        )

    return "".join(summary_lines)


def frequent_themes_section(df: pd.DataFrame, top_n: int = 20) -> str:
    # Use both abstract and title cleaned text for theme extraction
    texts = []
    if "abstract_clean" in df.columns:
        texts.extend(df["abstract_clean"].astype(str).tolist())
    if "title_clean" in df.columns:
        texts.extend(df["title_clean"].astype(str).tolist())

    kw_pairs = top_keywords_from_texts(texts, top_n=top_n)
    md = ["## Frequently occurring research themes\n"]
    md.append(_format_top_list(kw_pairs, limit=top_n))
    md.append("\n")

    # Also include bi/tri-grams as topics
    topics_df = most_common_topics(df, text_column="abstract_clean", ngram_range=(2, 3), top_n=20)
    if not topics_df.empty:
        md.append("### Common multi-word topics\n")
        for _, row in topics_df.head(10).iterrows():
            md.append(f"- **{row['topic']}** — {int(row['count'])} occurrences\n")
    return "".join(md)


def common_datasets_section(df: pd.DataFrame, limit: int = 20) -> str:
    texts = df["abstract_clean"].astype(str).tolist() if "abstract_clean" in df.columns else []
    counts = _count_entity_mentions(texts, COMMON_DATASETS)
    if not counts:
        return "## Common datasets\n\n_No dataset mentions detected._\n"
    items = counts.most_common(limit)
    md = ["## Common datasets\n\n"]
    for k, v in items:
        md.append(f"- **{k}** — {v} mentions\n")
    return "".join(md)


def common_benchmarks_section(df: pd.DataFrame, limit: int = 20) -> str:
    texts = df["abstract_clean"].astype(str).tolist() if "abstract_clean" in df.columns else []
    counts = _count_entity_mentions(texts, COMMON_BENCHMARKS)
    if not counts:
        return "## Frequently referenced benchmarks\n\n_No benchmark mentions detected._\n"
    items = counts.most_common(limit)
    md = ["## Frequently referenced benchmarks\n\n"]
    for k, v in items:
        md.append(f"- **{k}** — {v} mentions\n")
    return "".join(md)


def common_metrics_section(df: pd.DataFrame, limit: int = 20) -> str:
    texts = df["abstract_clean"].astype(str).tolist() if "abstract_clean" in df.columns else []
    counts = _count_entity_mentions(texts, COMMON_METRICS)
    if not counts:
        return "## Common evaluation metrics\n\n_No metric mentions detected._\n"
    items = counts.most_common(limit)
    md = ["## Common evaluation metrics\n\n"]
    for k, v in items:
        md.append(f"- **{k}** — {v} mentions\n")
    return "".join(md)


def key_observations_section(df: pd.DataFrame) -> str:
    authors_df = compute_most_common_authors(df, top_n=10)
    obs = ["## Key observations\n\n"]
    obs.append("- Many papers cluster around the following authors/groups (top 10):\n")
    for _, row in authors_df.iterrows():
        obs.append(f"  - {row['author']}: {int(row['count'])} papers\n")
    obs.append("\n- Topic extraction and keyword frequencies are provided above; these reflect repeated empirical focuses across the corpus.\n")
    return "".join(obs)


def limitations_section() -> str:
    return (
        "## Limitations\n\n"
        "- The report is generated from cleaned abstracts and titles only; full-text analysis may reveal additional topics and evaluation setups.\n"
        "- Entity detection for datasets/benchmarks/metrics uses a curated list and substring matching; false positives/negatives are possible.\n"
        "- Tokenization and keyword extraction are simplistic (whitespace-based); more advanced NLP (TF-IDF, phrase detection, named entity recognition) could improve topic identification.\n"
    )


def future_work_section() -> str:
    return (
        "## Future work\n\n"
        "- Expand entity detection using named-entity recognition and curated gazetteers for datasets and benchmarks.\n"
        "- Integrate TF-IDF and topic modeling (LDA, NMF) to surface latent research themes.\n"
        "- Correlate topics with empirical practices (datasets, metrics) and track trends over time.\n"
        "- Add visualization of trends and networks (co-authorship, topic co-occurrence) and include them in reports/ and graphs/.\n"
    )


def generate_report(input_path: Optional[Path] = None, output_path: Optional[Path] = None) -> Path:
    input_path = input_path or DEFAULT_INPUT
    output_path = output_path or OUTPUT_PATH
    df = _load_cleaned(input_path)

    logger.info("Generating literature review report")
    parts: List[str] = []
    parts.append(research_objective_section())
    parts.append("\n")
    parts.append(dataset_summary_section(df))
    parts.append("\n")
    parts.append(frequent_themes_section(df))
    parts.append("\n")
    parts.append(common_datasets_section(df))
    parts.append("\n")
    parts.append(common_benchmarks_section(df))
    parts.append("\n")
    parts.append(common_metrics_section(df))
    parts.append("\n")
    parts.append(key_observations_section(df))
    parts.append("\n")
    parts.append(limitations_section())
    parts.append("\n")
    parts.append(future_work_section())

    output_text = "\n".join(parts)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write(output_text)

    logger.info("Wrote literature review to %s", output_path)
    return output_path


if __name__ == "__main__":
    import argparse

